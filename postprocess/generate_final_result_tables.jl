#!/usr/bin/env julia

# Fail-closed generator for the two final system tables.  Stress-conditioned
# and equal-hour adequacy populations remain in separate column groups.

using CSV
using DataFrames
using Printf
using TOML
using SHA
include(joinpath(@__DIR__, "TestWindAcceptance.jl"))
using .TestWindAcceptance

const MODELS = ["M0", "M1", "M2", "M3", "M3-ClassMax", "M4", "M5",
                "Proposed-Tradeoff", "Proposed-Safety"]

length(ARGS) == 5 || error(
    "usage: generate_final_result_tables.jl RBTS_STRESS_SUMMARY RBTS_UNCONDITIONAL_SUMMARY RTS79_STRESS_SUMMARY RTS79_UNCONDITIONAL_SUMMARY OUTPUT_DIR")

tex_model(model::String) = replace(model,
    "M3-ClassMax" => "M3--ClassMax",
    "Proposed-Tradeoff" => "M6--Tradeoff",
    "Proposed-Safety" => "M6--Safety")

function tex_magnitude(value::Real)
    formatted = @sprintf("%.3g", value)
    if occursin('e', formatted)
        mantissa, exponent = split(formatted, 'e')
        return "\$$(mantissa)\\times10^{$(parse(Int, exponent))}\$"
    end
    return formatted
end

tex_time(value::Real) = value < 0.01 ? @sprintf("%.3f", value) : @sprintf("%.2f", value)

function read_verified(path::String, system::String, scope::String, states::Int)
    isfile(path) || error("missing summary: $path")
    manifest_path = replace(path, r"_summary\.csv$" => "_manifest.toml")
    isfile(manifest_path) || error("missing manifest: $manifest_path")
    manifest = TOML.parsefile(manifest_path)
    get(manifest, "test_wind_gate_version", "") == TEST_WIND_GATE_VERSION ||
        error("final tables require the test-wind acceptance correction")
    manifest["summary_file_sha256"] == bytes2hex(open(SHA.sha256, path)) ||
        error("summary hash mismatch")
    String(manifest["status"]) == "complete" || error("incomplete manifest")
    String(manifest["system"]) == system || error("system mismatch")
    String(manifest["scope"]) == scope || error("scope mismatch")
    Int(manifest["state_count"]) == states || error("state-count mismatch")
    if scope == "stress"
        Bool(manifest["all_rows_model_called"]) || error("precheck substitution detected")
    else
        String(manifest["policy_mode"]) ==
            "common_normal_dispatch_plus_emergency_activation" ||
            error("unverified equal-hour adequacy operating policy")
        Bool(manifest["raw_full_domain_all_models_called"]) ||
            error("missing full-domain all-model applicability audit")
        Bool(manifest["equal_hour_weights"]) || error("nonuniform equal-hour weights")
        Int(manifest["activation_state_count"]) +
            Int(manifest["outside_activation_state_count"]) == states ||
            error("activation-state accounting mismatch")
    end
    String.(manifest["models"]) == MODELS || error("manifest model mismatch")

    table = CSV.read(path, DataFrame)
    nrow(table) == length(MODELS) || error("summary row-count mismatch")
    String.(table.model) == MODELS || error("summary model order mismatch")
    all(String.(table.system) .== system) || error("summary system mismatch")
    all(String.(table.scope) .== scope) || error("summary scope mismatch")
    all(Int.(table.n_states) .== states) || error("summary state mismatch")
    return table
end

function row_for(table::DataFrame, model::String)
    rows = table[String.(table.model) .== model, :]
    nrow(rows) == 1 || error("missing or duplicate $model")
    return rows[1, :]
end

function write_system_table(path::String, system::String, stress::DataFrame,
                            unconditional::DataFrame, stress_n::Int,
                            unconditional_n::Int)
    label = lowercase(system)
    open(path, "w") do io
        println(io, "% Auto-generated by generate_final_result_tables.jl; do not edit.")
        println(io, "\\begin{table*}[t]")
        println(io, "\\caption{$system common-state results: $stress_n stress states and $unconditional_n equal-hour adequacy states under the common-normal-dispatch/emergency-activation policy.  Safety events include conservative nonacceptance penalties.  Maximum excess and median online time use accepted stress solves.  Nonacceptance counts are listed as stress/adequacy; EUE is annualized.}")
        println(io, "\\label{tab:$(label)-final-results}")
        println(io, "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.7pt}")
        println(io, "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}lrrrrrrrrr@{}}")
        println(io, "\\toprule")
        println(io, "& \\multicolumn{4}{c}{Resource-pressure stress test} & \\multicolumn{3}{c}{Equal-hour adequacy} & \\multicolumn{2}{c}{Audit and computation} \\\\")
        println(io, "\\cmidrule(lr){2-5}\\cmidrule(lr){6-8}\\cmidrule(lr){9-10}")
        println(io, "Model & SCMS & LOLP\$_{\\rm stress}\$ & Safety & \\shortstack{Max. accepted\\\\excess} & EDNS & LOLP & EUE & \\shortstack{Nonacc.\\\\stress/adeq.} & \$T_{\\rm on}\$ \\\\")
        println(io, "& (MW) & & events & (MW) & (MW) & & (GWh/yr) & & (s) \\\\")
        println(io, "\\midrule")
        for model in MODELS
            s = row_for(stress, model)
            u = row_for(unconditional, model)
            @printf(io,
                "%s & %.2f & %.3f & %d/%d & %s & %.2f & %.3f & %.2f & %d/%d & %s \\\\\n",
                tex_model(model), Float64(s.mean_shed_mw), Float64(s.lolp),
                Int(s.safety_event_count), stress_n,
                tex_magnitude(s.accepted_max_excess_mw), Float64(u.mean_shed_mw),
                Float64(u.lolp), Float64(u.eue_mwh_per_year) / 1000.0,
                Int(s.nonaccepted), Int(u.nonaccepted), tex_time(s.median_online_s))
        end
        println(io, "\\bottomrule")
        println(io, "\\end{tabular*}")
        println(io, "\\end{table*}")
    end
end

function main()
    rbts_stress = read_verified(normpath(ARGS[1]), "RBTS", "stress", 1000)
    rbts_unconditional = read_verified(normpath(ARGS[2]), "RBTS", "unconditional", 500)
    rts_stress = read_verified(normpath(ARGS[3]), "RTS79", "stress", 500)
    rts_unconditional = read_verified(normpath(ARGS[4]), "RTS79", "unconditional", 500)
    output_dir = normpath(ARGS[5]); mkpath(output_dir)

    write_system_table(joinpath(output_dir, "TABLE_RBTS_FINAL.tex"), "RBTS",
        rbts_stress, rbts_unconditional, 1000, 500)
    write_system_table(joinpath(output_dir, "TABLE_RTS79_FINAL.tex"), "RTS79",
        rts_stress, rts_unconditional, 500, 500)

    combined = vcat(rbts_stress, rbts_unconditional, rts_stress,
                    rts_unconditional; cols = :union)
    CSV.write(joinpath(output_dir, "final_all_system_summary.csv"), combined)
    println("Final table bundle: ", abspath(output_dir))
end

main()
